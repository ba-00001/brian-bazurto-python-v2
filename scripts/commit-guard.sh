#!/usr/bin/env bash
# Mirror of .claude/agents/commit-guard.md — blocks a push with the wrong identity or attribution.
set -u
ALLOWED_EMAIL="124537281+ba-00001@users.noreply.github.com"
ALLOWED_NAMES="ba-00001|Brian Bazurto"
FORBIDDEN_EMAILS="jeanstephane@aloyd.com"
WORDS='co-authored-by:|(^|[^.[:alnum:]])(claude|anthropic|chatgpt|copilot)([^[:alnum:]]|$)|gpt-|generated with|generated by|auto-generated|\[bot\]'
fail=0

email=$(git config user.email || true)
if [ "$email" != "$ALLOWED_EMAIL" ]; then
  echo "HARD: git user.email is '$email' (must be $ALLOWED_EMAIL)"; fail=1
fi

range="${1:-@{u}..HEAD}"
git rev-parse --verify -q "@{u}" >/dev/null 2>&1 || range="HEAD"

while IFS='|' read -r sha an ae cn ce; do
  for e in "$ae" "$ce"; do
    [ "$e" = "$ALLOWED_EMAIL" ] || { echo "HARD: $sha uses email $e"; fail=1; }
    echo "$e" | grep -qiE "$FORBIDDEN_EMAILS" && { echo "HARD: $sha uses forbidden email $e"; fail=1; }
  done
  for n in "$an" "$cn"; do
    echo "$n" | grep -qE "^($ALLOWED_NAMES)$" || { echo "HARD: $sha uses name '$n'"; fail=1; }
  done
done < <(git log "$range" --format='%h|%an|%ae|%cn|%ce' 2>/dev/null)

if git log "$range" --format='%B' 2>/dev/null | grep -qiE "$WORDS"; then
  echo "HARD: attribution text found in commit messages"; fail=1
fi
if git diff --cached | grep -E '^\+[^+]' | grep -qiE "$WORDS"; then
  echo "SOFT: attribution-like words in staged diff"
fi

if [ $fail -ne 0 ]; then echo "commit-guard: FAIL"; exit 1; fi
echo "commit-guard: PASS"
